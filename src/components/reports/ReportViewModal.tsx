import React, { useState, useEffect } from 'react';
import { X, Download, Mail, MessageSquare, CheckCircle, RefreshCw, FileText, AlertTriangle } from 'lucide-react';
import { Job, Customer, Inspector, Equipment, CompanySettings } from '../../types';
import { generateNDTPdfReport } from '../../utils/pdfGenerator';
import { isL3Certified } from '../../utils/validation';

interface ReportViewModalProps {
  isOpen: boolean;
  onClose: () => void;
  job: Job;
  customer?: Customer;
  inspector?: Inspector;
  supervisor?: Inspector;
  equipmentList?: Equipment[];
  settings: CompanySettings;
}

export const ReportViewModal: React.FC<ReportViewModalProps> = ({
  isOpen,
  onClose,
  job,
  customer,
  inspector,
  supervisor,
  equipmentList = [],
  settings
}) => {
  const [pdfBlobUrl, setPdfBlobUrl] = useState<string | null>(null);
  const [isGenerating, setIsGenerating] = useState(false);
  const certified = isL3Certified(job);

  const buildPdf = async () => {
    setIsGenerating(true);
    try {
      const doc = await generateNDTPdfReport(job, customer, inspector, equipmentList, settings, supervisor);
      const blob = doc.output('blob');
      if (pdfBlobUrl) {
        URL.revokeObjectURL(pdfBlobUrl);
      }
      const url = URL.createObjectURL(blob);
      setPdfBlobUrl(url);
    } catch (err) {
      console.error('Failed to generate PDF:', err);
    } finally {
      setIsGenerating(false);
    }
  };

  useEffect(() => {
    if (isOpen) {
      buildPdf();
    }
    return () => {
      if (pdfBlobUrl) {
        URL.revokeObjectURL(pdfBlobUrl);
      }
    };
  }, [isOpen, job.id, job.l3ReviewStatus]);

  if (!isOpen) return null;

  const handleDownload = async () => {
    const doc = await generateNDTPdfReport(job, customer, inspector, equipmentList, settings, supervisor);
    const label = certified ? 'Inspection_Certificate' : 'Draft_Report_Pending_L3';
    const filename = `${job.reportNumber || job.jobNumber}_${label}.pdf`;
    doc.save(filename);
  };

  const handleEmailShare = () => {
    if (!certified) {
      alert('Share as certificate is blocked until Level 3 approves. You can still download the draft report.');
      return;
    }
    const site = customer?.sites.find(s => s.id === job.siteId);
    const subject = encodeURIComponent(`NDT Inspection Certificate: ${job.reportNumber || job.jobNumber} - ${job.method} (${job.overallResult})`);
    const body = encodeURIComponent(
      `Dear ${customer?.contactPerson || 'Client'},\n\nPlease find the inspection details for Job #${job.jobNumber} (${job.scope}) completed on ${job.inspectionDate}.\n\nOverall Result: ${job.overallResult}\nCustomer: ${customer?.companyName}\nSite: ${site?.name || 'On Site'}\nInspector: ${inspector?.fullName} (${inspector?.certNumber})\n\nOfficial PDF certificate attached / generated via Apex NDT Field Inspect.\n\nRegards,\n${settings.companyName}\n${settings.phone}`
    );
    window.location.href = `mailto:${customer?.email || ''}?subject=${subject}&body=${body}`;
  };

  const handleWhatsAppShare = () => {
    if (!certified) {
      alert('Share as certificate is blocked until Level 3 approves. You can still download the draft report.');
      return;
    }
    const site = customer?.sites.find(s => s.id === job.siteId);
    const text = encodeURIComponent(
      `*NDT Inspection Certificate: ${job.reportNumber || job.jobNumber}*\nClient: ${customer?.companyName}\nSite: ${site?.name || 'On Site'}\nMethod: ${job.method}\nOverall Result: *${job.overallResult}*\nInspector: ${inspector?.fullName}\nDate: ${job.inspectionDate}\n\nGenerated by ${settings.companyName}`
    );
    window.open(`https://wa.me/?text=${text}`, '_blank');
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-slate-950/85 backdrop-blur-md p-2 sm:p-4 overflow-hidden">
      <div className="bg-slate-900 border border-slate-800 w-full max-w-5xl h-[94vh] rounded-2xl shadow-2xl flex flex-col overflow-hidden animate-in fade-in zoom-in-95 duration-200">
        
        <div className="flex items-center justify-between px-5 py-3.5 border-b border-slate-800 bg-slate-900/90">
          <div className="flex items-center gap-3">
            <div className="w-9 h-9 rounded-xl bg-sky-500/20 text-sky-400 flex items-center justify-center font-bold">
              <FileText className="w-5 h-5" />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <h3 className="font-extrabold text-base text-white">
                  {certified ? 'Inspection Report Certificate' : 'Draft Report — Pending L3'}
                </h3>
                <span className={`px-2 py-0.5 rounded text-xs font-bold ${
                  certified
                    ? 'bg-emerald-500/20 text-emerald-400 border border-emerald-500/30'
                    : 'bg-amber-500/20 text-amber-300 border border-amber-500/30'
                }`}>
                  {certified ? 'L3 CERTIFIED' : 'DRAFT'}
                </span>
                <span className={`px-2 py-0.5 rounded text-xs font-bold ${
                  job.overallResult === 'PASS'
                    ? 'bg-emerald-500/20 text-emerald-400 border border-emerald-500/30'
                    : job.overallResult === 'FAIL'
                    ? 'bg-rose-500/20 text-rose-400 border border-rose-500/30'
                    : 'bg-amber-500/20 text-amber-400 border border-amber-500/30'
                }`}>
                  {job.overallResult}
                </span>
              </div>
              <p className="text-xs text-slate-400">
                {job.reportNumber || 'REP-PREVIEW'} • {job.jobNumber} • {customer?.companyName}
              </p>
            </div>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={buildPdf}
              title="Regenerate PDF"
              className="p-2 rounded-lg text-slate-400 hover:text-white hover:bg-slate-800 transition-colors"
            >
              <RefreshCw className={`w-4 h-4 ${isGenerating ? 'animate-spin text-sky-400' : ''}`} />
            </button>

            <button
              onClick={onClose}
              className="p-2 rounded-lg text-slate-400 hover:text-white hover:bg-slate-800 transition-colors"
            >
              <X className="w-5 h-5" />
            </button>
          </div>
        </div>

        {!certified && (
          <div className="px-5 py-2 bg-amber-500/10 border-b border-amber-500/30 text-xs text-amber-200 flex items-center gap-2">
            <AlertTriangle className="w-3.5 h-3.5 shrink-0" />
            Draft only — share-as-certificate is blocked until Level 3 approval. Download is allowed for demo review.
          </div>
        )}

        <div className="flex-1 bg-slate-950 p-2 sm:p-4 overflow-hidden relative flex items-center justify-center">
          {isGenerating && (
            <div className="absolute inset-0 bg-slate-950/70 backdrop-blur-xs flex flex-col items-center justify-center z-10 text-sky-400">
              <div className="w-8 h-8 border-3 border-sky-400 border-t-transparent rounded-full animate-spin mb-3"></div>
              <p className="text-sm font-semibold">Generating high-res South African NDT Certificate...</p>
            </div>
          )}

          {pdfBlobUrl ? (
            <iframe
              src={pdfBlobUrl}
              title="NDT Inspection Certificate Preview"
              className="w-full h-full rounded-xl shadow-2xl border border-slate-800 bg-white"
            />
          ) : (
            <div className="text-slate-500 text-sm">Preparing document preview...</div>
          )}
        </div>

        <div className="px-5 py-3.5 bg-slate-900 border-t border-slate-800 flex flex-wrap items-center justify-between gap-3">
          <div className="flex items-center gap-2 text-xs text-slate-400">
            {certified ? (
              <>
                <CheckCircle className="w-4 h-4 text-emerald-400" />
                <span>L3 certified demo report — ISO 9712-shaped multi-sign workflow</span>
              </>
            ) : (
              <>
                <AlertTriangle className="w-4 h-4 text-amber-400" />
                <span>Pending Level 3 — not a certificate yet</span>
              </>
            )}
          </div>

          <div className="flex items-center gap-2.5">
            <button
              type="button"
              onClick={handleWhatsAppShare}
              disabled={!certified}
              className={`inline-flex items-center gap-1.5 px-3.5 py-2 rounded-xl font-bold text-xs border active:scale-95 transition-all ${
                certified
                  ? 'bg-emerald-600/20 hover:bg-emerald-600/30 text-emerald-400 border-emerald-500/30'
                  : 'bg-slate-800 text-slate-500 border-slate-700 cursor-not-allowed opacity-60'
              }`}
            >
              <MessageSquare className="w-4 h-4" />
              <span>WhatsApp</span>
            </button>

            <button
              type="button"
              onClick={handleEmailShare}
              disabled={!certified}
              className={`inline-flex items-center gap-1.5 px-3.5 py-2 rounded-xl font-semibold text-xs border active:scale-95 transition-all ${
                certified
                  ? 'bg-slate-800 hover:bg-slate-700 text-slate-200 border-slate-700'
                  : 'bg-slate-800 text-slate-500 border-slate-700 cursor-not-allowed opacity-60'
              }`}
            >
              <Mail className="w-4 h-4" />
              <span>Email Report</span>
            </button>

            <button
              type="button"
              onClick={handleDownload}
              className="inline-flex items-center gap-2 px-5 py-2.5 rounded-xl bg-gradient-to-r from-sky-600 to-cyan-500 hover:from-sky-500 hover:to-cyan-400 text-white font-bold text-sm shadow-lg shadow-sky-500/25 active:scale-95 transition-all"
            >
              <Download className="w-4 h-4" />
              <span>{certified ? 'Download Certificate' : 'Download Draft'}</span>
            </button>
          </div>
        </div>

      </div>
    </div>
  );
};
